/**
 * 「这个文件名看着像日志吗」——**纯按名字判，不看内容**。
 *
 * # 它不参与「用哪种模式打开」
 *
 * 那个判定在 Rust 侧的 `logengine::probe`，判据是体积 / 行数 / 最长行 / 二进制，
 * 一律不看文件名 —— 一个叫 `a.txt` 的 2GB 文件照样得走 mmap，一个叫
 * `app.log` 的 3KB 文件用 CodeMirror 打开完全没问题。**那条判据是对的，不动。**
 *
 * 这里判的是另一件事：**状态栏那个「编辑模式 ⇄」按钮该不该出现。**
 * 它原来对每一个打开的文件都在，而绝大多数文件根本不存在「切到日志模式」
 * 这个需求 —— 一个 `.ts` 文件切过去只会得到一份没有高亮、不能编辑的文本。
 * 一个永远在、而九成场合按下去只有坏处的按钮，等于把状态栏那格白占了。
 *
 * # 藏起来不等于做不了
 *
 * 菜单里的「切换编辑 / 日志模式」（`toggle-mode`）对**任何**文件都还在。
 * 这里只决定「要不要把它顶到状态栏上」——常用场景给一个一眼看见的按钮，
 * 罕见场景留在菜单里。
 *
 * # 名单为什么是这几条
 *
 * 宁可漏判也不要错判：`.txt` `.json` `.csv` 都可能是日志，但更可能不是，
 * 收进来就等于「按钮又回到了到处都在」。收的是**只可能是日志**的那几种。
 */

/**
 * `.log` / `.out` / `.err`，允许后面再跟一段轮转后缀。
 *
 * 轮转的形状实际见过这几种，都得认：
 * `app.log.1`、`app.log.2026-09-10`、`app.log.gz`、`app.2026-09-10.log`。
 * 最后一种靠 `\.log$` 本身就中了，前三种靠后面那个可选段。
 */
const LOG_EXT = /\.(log|out|err)(\.[\w-]+)*$/i;

/** 没有扩展名的那几个系统日志。`system.log` / `catalina.out` 已经被上面那条收了 */
const LOG_BARE = /^(messages|syslog|dmesg)$/i;

/** `path` 可以是全路径也可以只是文件名 */
export function isLogName(path: string): boolean {
  const name = path.slice(path.lastIndexOf("/") + 1);
  return LOG_EXT.test(name) || LOG_BARE.test(name);
}
